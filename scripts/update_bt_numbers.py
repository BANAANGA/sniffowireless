#!/usr/bin/env python3
"""Regenerate sniffowireless/static/btnumbers.js from the Bluetooth SIG's published assigned numbers.

    python3 scripts/update_bt_numbers.py

Fetches the UUID lists (member services, standard services, Classic service classes, standards bodies) from the SIG's public
repository and keeps only the numbers and names. Run it now and then: the SIG registers new members all the time.
"""
import json
import re
import sys
import urllib.request

BASE = "https://bitbucket.org/bluetooth-SIG/public/raw/main/assigned_numbers/uuids/"
FILES = {"member": "member_uuids.yaml", "service": "service_uuids.yaml", "serviceClass": "service_class.yaml", "sdo": "sdo_uuids.yaml"}
ENTRY = re.compile(r"-\s*uuid:\s*0x([0-9A-Fa-f]{4})\s*\n\s*name:\s*(.+?)\s*\n")
OUT = __file__.rsplit("/scripts/", 1)[0] + "/sniffowireless/static/btnumbers.js"


def main():
    data = {}
    for key, name in FILES.items():
        text = urllib.request.urlopen(BASE + name, timeout=30).read().decode("utf-8")
        found = {m.group(1).lower(): m.group(2).strip().strip("'\"") for m in ENTRY.finditer(text)}
        if len(found) < 10:
            sys.exit(f"{name}: only {len(found)} entries found, the format may have changed")
        data[key] = dict(sorted(found.items()))
        print(f"{name}: {len(found)} numbers")
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("'use strict';\n/* Bluetooth SIG assigned 16-bit numbers (member services, standard services, Classic service classes, standards bodies).\n"
                "   Generated by scripts/update_bt_numbers.py from the SIG's public Assigned Numbers; do not edit by hand. */\n"
                f"const BT_NUMBERS = {body};\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
